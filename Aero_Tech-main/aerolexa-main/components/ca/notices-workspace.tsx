"use client";

import { AlertTriangle, BellRing, FileWarning, Plus } from "lucide-react";
import { useCallback, useEffect, useState } from "react";

import { Button } from "@/components/ui/button";
import { Input, Select, Textarea } from "@/components/ui/form";
import { Badge, Card, CardContent } from "@/components/ui/primitives";
import { api, errorMessage } from "@/lib/client/api";
import { NOTICE_TYPES } from "@/lib/notice-constants";

/**
 * GST notice register + reply drafting.
 *
 * Every notice is persisted (number, deadline, demand, reply history), so a
 * firm can answer "what is due this week and who owns it" without a
 * spreadsheet. The draft is generated by `gst-notice-workflow` and saved as a
 * draft only — marking a reply filed stays a deliberate human action.
 */

interface NoticeDeadline {
  dueDate: string;
  daysLeft: number;
  status: "overdue" | "due" | "upcoming";
}

interface StoredNotice {
  id: string;
  noticeNumber: string;
  noticeDate: string;
  noticeType: string;
  authorityLevel: string;
  authorityName: string;
  authorityJurisdiction: string;
  gstin: string;
  entityName: string;
  period: string | null;
  subject: string;
  description: string;
  responseDueDate: string;
  status: string;
  priority: string;
  assignedTo: string | null;
}

interface EngineNotice {
  id: string;
  noticeNumber: string;
  noticeType: string;
  authorityLevel: string;
  authorityName: string;
  authorityJurisdiction: string;
  gstin: string;
  entityName: string;
  period?: string;
  financialYear?: string;
  subject: string;
  description: string;
  sections: string[];
  rules: string[];
  demandedAmount?: { tax: number; interest: number; penalty: number; total: number };
  responseDueDate: string;
  status: string;
  priority: string;
  tags: string[];
  noticeDate: string;
}

interface NoticeRow extends StoredNotice {
  notice: EngineNotice;
  deadline: NoticeDeadline;
  _count?: { responses: number };
}

interface ResponseRow {
  id: string;
  responseNumber: string;
  responseDate: string;
  responseType: string;
  status: string;
  content: string;
  createdAt: string;
}

interface Draft {
  responseNumber: string;
  responseDate: string;
  responseType: string;
  status: string;
  content: {
    facts: string;
    legalArguments: string[];
    evidenceReferences: string[];
    computations: { head: string; demanded: number; admitted: number; disputed: number; basis: string }[];
    prayers: string[];
  };
  attachments: { name: string; type: string; ref: string }[];
  filingMode: string;
}

const STATUSES = [
  "received",
  "under-review",
  "response-drafting",
  "response-filed",
  "personal-hearing",
  "order-received",
  "appeal-filed",
  "escalated",
  "closed",
];

const AUTHORITIES = ["proper-officer", "jc", "ac", "dc", "commissioner", "aat", "high-court", "supreme-court"];

const PRIORITIES = ["low", "medium", "high", "critical"];

const TONE: Record<string, "success" | "warning" | "critical" | "default" | "info"> = {
  received: "warning",
  "under-review": "info",
  "response-drafting": "info",
  "response-filed": "success",
  "personal-hearing": "warning",
  "order-received": "default",
  "appeal-filed": "info",
  closed: "success",
  escalated: "critical",
};

function formatDeadline(deadline: NoticeDeadline): string {
  if (deadline.daysLeft < 0) return `${Math.abs(deadline.daysLeft)} day(s) overdue`;
  if (deadline.daysLeft === 0) return "due today";
  return `${deadline.daysLeft} day(s) left`;
}

function formatInrMinor(minor: number): string {
  return (minor / 100).toLocaleString("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2,
  });
}

const EMPTY_FORM = {
  noticeNumber: "",
  noticeDate: new Date().toISOString().slice(0, 10),
  noticeType: "asmt-10",
  authorityLevel: "proper-officer",
  authorityName: "",
  authorityJurisdiction: "",
  gstin: "",
  entityName: "",
  period: "",
  subject: "",
  description: "",
  sections: "",
  rules: "",
  demandedTax: "",
  demandedInterest: "",
  demandedPenalty: "",
  responseDueDate: "",
  priority: "medium",
};

export function NoticesWorkspace() {
  const [notices, setNotices] = useState<NoticeRow[]>([]);
  const [selectedId, setSelectedId] = useState("");
  const [responses, setResponses] = useState<ResponseRow[]>([]);
  const [detail, setDetail] = useState<NoticeRow | null>(null);
  const [draft, setDraft] = useState<Draft | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [showForm, setShowForm] = useState(false);
  const [form, setForm] = useState(EMPTY_FORM);

  const loadNotices = useCallback(async () => {
    setLoading(true);
    try {
      const data = await api<{ notices: NoticeRow[] }>("/api/gst/notices");
      setNotices(data.notices ?? []);
      setSelectedId((current) => current || data.notices?.[0]?.id || "");
      setError(null);
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void loadNotices();
  }, [loadNotices]);

  const loadDetail = useCallback(async (id: string) => {
    if (!id) return;
    try {
      const data = await api<{ notice: StoredNotice; engineNotice: EngineNotice; deadline: NoticeDeadline }>(
        `/api/gst/notices/${id}`,
      );
      const listed = await api<{ responses: ResponseRow[] }>(`/api/gst/notices/${id}/responses`);
      setDetail({ ...data.notice, notice: data.engineNotice, deadline: data.deadline });
      setResponses(listed.responses ?? []);
      setDraft(null);
      setError(null);
    } catch (err) {
      setError(errorMessage(err));
    }
  }, []);

  useEffect(() => {
    void loadDetail(selectedId);
  }, [selectedId, loadDetail]);

  const createNotice = async () => {
    setBusy(true);
    setError(null);
    try {
      await api("/api/gst/notices", {
        method: "POST",
        body: JSON.stringify({
          noticeNumber: form.noticeNumber,
          noticeDate: form.noticeDate,
          noticeType: form.noticeType,
          authorityLevel: form.authorityLevel,
          authorityName: form.authorityName,
          authorityJurisdiction: form.authorityJurisdiction,
          gstin: form.gstin.toUpperCase(),
          entityName: form.entityName,
          period: form.period || null,
          subject: form.subject,
          description: form.description,
          sections: form.sections
            .split(",")
            .map((s) => s.trim())
            .filter(Boolean),
          rules: form.rules
            .split(",")
            .map((s) => s.trim())
            .filter(Boolean),
          demandedTax: form.demandedTax ? Number(form.demandedTax) : undefined,
          demandedInterest: form.demandedInterest ? Number(form.demandedInterest) : undefined,
          demandedPenalty: form.demandedPenalty ? Number(form.demandedPenalty) : undefined,
          responseDueDate: form.responseDueDate,
          priority: form.priority,
          tags: [],
        }),
      });
      setNotice("Notice recorded with its reply deadline.");
      setShowForm(false);
      setForm(EMPTY_FORM);
      await loadNotices();
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const changeStatus = async (status: string) => {
    if (!detail) return;
    setBusy(true);
    try {
      await api(`/api/gst/notices/${detail.id}`, { method: "PATCH", body: JSON.stringify({ status }) });
      setNotice(`Marked ${status}.`);
      await loadNotices();
      await loadDetail(detail.id);
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const generate = async () => {
    if (!detail) return;
    setBusy(true);
    setError(null);
    try {
      // The generator boundary is rupees; the store holds paise.
      const engine = detail.notice;
      const demanded = engine.demandedAmount
        ? {
            tax: engine.demandedAmount.tax / 100,
            interest: engine.demandedAmount.interest / 100,
            penalty: engine.demandedAmount.penalty / 100,
            total: engine.demandedAmount.total / 100,
          }
        : undefined;
      const data = await api<{ response: Draft }>("/api/gst/notices/generate-response", {
        method: "POST",
        body: JSON.stringify({
          notice: { ...engine, demandedAmount: demanded },
          linkedArtifacts: [],
        }),
      });
      setDraft(data.response);
      setNotice("Draft generated. Review it, then save it to the notice.");
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const saveDraft = async () => {
    if (!detail || !draft) return;
    setBusy(true);
    setError(null);
    try {
      await api(`/api/gst/notices/${detail.id}/responses`, {
        method: "POST",
        body: JSON.stringify({
          responseNumber: draft.responseNumber,
          responseDate: draft.responseDate,
          responseType: draft.responseType,
          status: "draft",
          content: draft.content,
          attachments: draft.attachments,
          filingMode: draft.filingMode,
        }),
      });
      setNotice("Response saved as a draft. The notice is now in response-drafting.");
      setDraft(null);
      await loadDetail(detail.id);
      await loadNotices();
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const overdue = notices.filter((n) => n.deadline.status === "overdue").length;
  const dueSoon = notices.filter((n) => n.deadline.status === "due").length;

  return (
    <div className="space-y-4">
      {error && (
        <p className="flex items-start gap-2 rounded-md border border-danger/40 bg-danger/10 px-3 py-2 text-sm">
          <AlertTriangle aria-hidden className="mt-0.5 size-4 shrink-0 text-danger" />
          <span>{error}</span>
        </p>
      )}
      {notice && (
        <p className="rounded-md border border-emerald/40 bg-emerald/10 px-3 py-2 text-sm text-foreground">{notice}</p>
      )}

      <div className="flex flex-wrap items-center gap-3 text-sm">
        <span className="text-muted">Notice register</span>
        <Badge variant="critical">{overdue} overdue</Badge>
        <Badge variant="warning">{dueSoon} due this week</Badge>
        <span className="text-caption text-muted">
          {notices.length} notice{notices.length === 1 ? "" : "s"} on record
        </span>
        <Button
          className="ml-auto"
          size="sm"
          variant="secondary"
          onClick={() => setShowForm((v) => !v)}
          icon={<Plus aria-hidden className="size-4" />}
        >
          {showForm ? "Cancel" : "Record notice"}
        </Button>
      </div>

      {showForm && (
        <Card>
          <CardContent className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
            <Input
              label="Notice number"
              value={form.noticeNumber}
              onChange={(e) => setForm((f) => ({ ...f, noticeNumber: e.target.value }))}
              placeholder="ASMT-10/2026/0042"
            />
            <Input
              label="Notice date"
              type="date"
              value={form.noticeDate}
              onChange={(e) => setForm((f) => ({ ...f, noticeDate: e.target.value }))}
            />
            <Select
              label="Notice type"
              value={form.noticeType}
              onChange={(e) => setForm((f) => ({ ...f, noticeType: e.target.value }))}
              options={NOTICE_TYPES.map((t) => ({ value: t, label: t.toUpperCase() }))}
            />
            <Select
              label="Authority"
              value={form.authorityLevel}
              onChange={(e) => setForm((f) => ({ ...f, authorityLevel: e.target.value }))}
              options={AUTHORITIES.map((a) => ({ value: a, label: a }))}
            />
            <Input
              label="Authority name"
              value={form.authorityName}
              onChange={(e) => setForm((f) => ({ ...f, authorityName: e.target.value }))}
              placeholder="State Tax Officer, Ward 4"
            />
            <Input
              label="Jurisdiction"
              value={form.authorityJurisdiction}
              onChange={(e) => setForm((f) => ({ ...f, authorityJurisdiction: e.target.value }))}
              placeholder="Mumbai South"
            />
            <Input
              label="GSTIN"
              value={form.gstin}
              onChange={(e) => setForm((f) => ({ ...f, gstin: e.target.value.toUpperCase() }))}
              maxLength={15}
              placeholder="27AAPFU0939F1ZV"
            />
            <Input
              label="Entity"
              value={form.entityName}
              onChange={(e) => setForm((f) => ({ ...f, entityName: e.target.value }))}
              placeholder="Client Pvt Ltd"
            />
            <Input
              label="Tax period (yyyy-mm)"
              value={form.period}
              onChange={(e) => setForm((f) => ({ ...f, period: e.target.value }))}
              placeholder="2026-03"
            />
            <Input
              label="Subject"
              value={form.subject}
              onChange={(e) => setForm((f) => ({ ...f, subject: e.target.value }))}
              placeholder="Scrutiny of GSTR-3B for March 2026"
            />
            <Input
              label="Sections (comma separated)"
              value={form.sections}
              onChange={(e) => setForm((f) => ({ ...f, sections: e.target.value }))}
              placeholder="61, 16(2)(aa)"
            />
            <Input
              label="Rules (comma separated)"
              value={form.rules}
              onChange={(e) => setForm((f) => ({ ...f, rules: e.target.value }))}
              placeholder="99, 36(4)"
            />
            <Input
              label="Demanded tax (₹)"
              inputMode="decimal"
              value={form.demandedTax}
              onChange={(e) => setForm((f) => ({ ...f, demandedTax: e.target.value }))}
            />
            <Input
              label="Interest (₹)"
              inputMode="decimal"
              value={form.demandedInterest}
              onChange={(e) => setForm((f) => ({ ...f, demandedInterest: e.target.value }))}
            />
            <Input
              label="Penalty (₹)"
              inputMode="decimal"
              value={form.demandedPenalty}
              onChange={(e) => setForm((f) => ({ ...f, demandedPenalty: e.target.value }))}
            />
            <Input
              label="Reply due date"
              type="date"
              value={form.responseDueDate}
              onChange={(e) => setForm((f) => ({ ...f, responseDueDate: e.target.value }))}
            />
            <Select
              label="Priority"
              value={form.priority}
              onChange={(e) => setForm((f) => ({ ...f, priority: e.target.value }))}
              options={PRIORITIES.map((p) => ({ value: p, label: p }))}
            />
            <div className="sm:col-span-2 lg:col-span-3">
              <Textarea
                label="Description"
                rows={2}
                value={form.description}
                onChange={(e) => setForm((f) => ({ ...f, description: e.target.value }))}
                placeholder="What the officer has asked for."
              />
            </div>
            <div className="sm:col-span-2 lg:col-span-3">
              <Button
                disabled={
                  busy ||
                  !form.noticeNumber.trim() ||
                  !form.authorityName.trim() ||
                  !form.authorityJurisdiction.trim() ||
                  form.gstin.length !== 15 ||
                  !form.entityName.trim() ||
                  !form.subject.trim() ||
                  !form.description.trim() ||
                  !form.responseDueDate
                }
                onClick={() => void createNotice()}
              >
                Record notice
              </Button>
            </div>
          </CardContent>
        </Card>
      )}

      <div className="grid gap-4 lg:grid-cols-[340px_1fr]">
        <div className="space-y-2">
          {loading && <p className="text-sm text-muted">Loading…</p>}
          {!loading && notices.length === 0 && (
            <p className="text-sm text-muted">
              No notices recorded. Record the first one and its reply deadline — the register is what stops a notice
              being missed.
            </p>
          )}
          {notices.map((n) => (
            <button
              key={n.id}
              onClick={() => setSelectedId(n.id)}
              className={`w-full rounded-lg border p-3 text-left transition ${
                n.id === selectedId ? "border-foreground bg-surface-2" : "border-line hover:border-muted"
              }`}
            >
              <div className="flex items-center gap-2">
                <Badge variant={TONE[n.status] ?? "default"}>{n.status}</Badge>
                {n.deadline.status === "overdue" && <Badge variant="critical">overdue</Badge>}
              </div>
              <div className="mt-1 text-sm font-medium text-foreground">
                {n.noticeNumber} · {n.noticeType.toUpperCase()}
              </div>
              <div className="text-caption text-muted">{n.entityName}</div>
              <div className="mt-1 text-caption text-muted">
                Due {n.responseDueDate} · {formatDeadline(n.deadline)}
              </div>
            </button>
          ))}
        </div>

        <div>
          {!detail ? (
            <Card>
              <CardContent>
                <p className="flex items-center gap-2 text-sm text-muted">
                  <FileWarning aria-hidden className="size-4" />
                  Select a notice to see its demand, deadline and replies.
                </p>
              </CardContent>
            </Card>
          ) : (
            <Card>
              <CardContent className="space-y-4">
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div>
                    <h2 className="text-h3 text-foreground">
                      {detail.noticeNumber} · {detail.noticeType.toUpperCase()}
                    </h2>
                    <p className="text-caption text-muted">
                      {detail.entityName} · {detail.gstin}
                      {detail.period ? ` · ${detail.period}` : ""}
                    </p>
                    <p className="text-caption text-muted">
                      {detail.authorityName}, {detail.authorityJurisdiction} · dated {detail.noticeDate}
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    <Select
                      aria-label="Notice status"
                      value={detail.status}
                      onChange={(e) => void changeStatus(e.target.value)}
                      options={STATUSES.map((s) => ({ value: s, label: s }))}
                    />
                  </div>
                </div>

                <div
                  className={`rounded-md border px-3 py-2 text-sm ${
                    detail.deadline.status === "overdue"
                      ? "border-danger/40 bg-danger/10"
                      : detail.deadline.status === "due"
                        ? "border-amber/40 bg-amber/10"
                        : "border-line bg-surface-2/60"
                  }`}
                >
                  <BellRing aria-hidden className="mr-2 inline size-4" />
                  Reply due {detail.responseDueDate} — {formatDeadline(detail.deadline)}
                  {detail.notice.demandedAmount
                    ? ` · demanded ${formatInrMinor(detail.notice.demandedAmount.total)}`
                    : ""}
                </div>

                <div className="space-y-1 text-sm">
                  <p className="font-medium text-foreground">{detail.subject}</p>
                  <p className="text-muted">{detail.description}</p>
                  {detail.notice.sections.length > 0 && (
                    <p className="text-caption text-muted">Sections: {detail.notice.sections.join(", ")}</p>
                  )}
                  {detail.notice.rules.length > 0 && (
                    <p className="text-caption text-muted">Rules: {detail.notice.rules.join(", ")}</p>
                  )}
                </div>

                <div className="flex flex-wrap items-center gap-2">
                  <Button size="sm" disabled={busy} onClick={() => void generate()}>
                    Generate reply draft
                  </Button>
                  {draft && (
                    <Button size="sm" variant="secondary" disabled={busy} onClick={() => void saveDraft()}>
                      Save as draft
                    </Button>
                  )}
                  <span className="text-caption text-muted">
                    The draft is a starting point; a partner reviews it before anything is filed.
                  </span>
                </div>

                {draft && (
                  <div className="space-y-3 rounded-md border border-line bg-surface-2/40 p-3 text-sm">
                    <p className="font-medium text-foreground">Draft {draft.responseNumber}</p>
                    <div>
                      <p className="text-caption font-medium text-muted">Facts</p>
                      <p className="text-foreground">{draft.content.facts}</p>
                    </div>
                    {draft.content.legalArguments.length > 0 && (
                      <div>
                        <p className="text-caption font-medium text-muted">Legal arguments</p>
                        <ul className="list-disc pl-5 text-foreground">
                          {draft.content.legalArguments.map((arg) => (
                            <li key={arg}>{arg}</li>
                          ))}
                        </ul>
                      </div>
                    )}
                    {draft.content.computations.length > 0 && (
                      <div className="overflow-x-auto">
                        <p className="text-caption font-medium text-muted">Computations (₹)</p>
                        <table className="w-full text-caption">
                          <thead>
                            <tr className="text-left text-muted">
                              <th className="py-1">Head</th>
                              <th className="py-1 text-right">Demanded</th>
                              <th className="py-1 text-right">Admitted</th>
                              <th className="py-1 text-right">Disputed</th>
                            </tr>
                          </thead>
                          <tbody>
                            {draft.content.computations.map((c, i) => (
                              <tr key={`${c.head}-${i}`} className="border-t border-line/60">
                                <td className="py-1">{c.head}</td>
                                <td className="py-1 text-right tabular-nums">{c.demanded}</td>
                                <td className="py-1 text-right tabular-nums">{c.admitted}</td>
                                <td className="py-1 text-right tabular-nums">{c.disputed}</td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                    )}
                    {draft.content.prayers.length > 0 && (
                      <div>
                        <p className="text-caption font-medium text-muted">Prayers</p>
                        <ul className="list-disc pl-5 text-foreground">
                          {draft.content.prayers.map((p) => (
                            <li key={p}>{p}</li>
                          ))}
                        </ul>
                      </div>
                    )}
                  </div>
                )}

                <div>
                  <h3 className="text-sm font-medium text-foreground">Saved replies ({responses.length})</h3>
                  {responses.length === 0 ? (
                    <p className="text-caption text-muted">No reply recorded yet.</p>
                  ) : (
                    <ul className="mt-2 divide-y divide-line">
                      {responses.map((r) => (
                        <li key={r.id} className="flex flex-wrap items-center gap-2 py-2 text-sm">
                          <Badge variant="outline">{r.status}</Badge>
                          <span className="text-foreground">{r.responseNumber}</span>
                          <span className="text-caption text-muted">
                            {r.responseType} · {r.responseDate}
                          </span>
                        </li>
                      ))}
                    </ul>
                  )}
                </div>
              </CardContent>
            </Card>
          )}
        </div>
      </div>
    </div>
  );
}
