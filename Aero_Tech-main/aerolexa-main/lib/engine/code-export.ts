/** Standalone scipy reproduction of a hypothesis test run in-app. */
export function hypothesisPythonScript(input: HypothesisExportInput, resultNotes?: string): string {
  const lines = header(
    `Reproduce Ledgerly hypothesis test: ${input.kind}`,
    "Identical scipy-equivalent statistic the in-app engine computed.",
  );
  if (input.kind === "t-test" && input.groups && input.groups.length === 2) {
    lines.push(
      `groups = ${json(input.groups)}`,
      "statistic, p_value = __import__('scipy').stats.ttest_ind(groups[0], groups[1], equal_var=True)",
      'print(f"t = {statistic:.6f}, p = {p_value:.6f}")',
    );
  } else if (input.kind === "chi-square" && input.table) {
    lines.push(
      `table = np.array(${json(input.table)})`,
      "from scipy.stats import chi2_contingency",
      "statistic, p_value, dof, expected = chi2_contingency(table)",
      'print(f"chi2 = {statistic:.6f}, p = {p_value:.6f}, dof = {dof}")',
    );
  } else if (input.kind === "anova" && input.groups) {
    lines.push(
      `groups = ${json(input.groups)}`,
      "from scipy.stats import f_oneway",
      "statistic, p_value = f_oneway(*groups)",
      'print(f"F = {statistic:.6f}, p = {p_value:.6f}")',
    );
  } else {
    lines.push("# Provide the test inputs (groups / contingency table) here.");
  }
  if (resultNotes) lines.push("", `# In-app notes: ${resultNotes}`);
  return lines.join("\n") + "\n";
}
