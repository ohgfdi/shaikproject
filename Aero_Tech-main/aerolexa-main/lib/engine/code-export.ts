/** Build the per-kind computation body for an analysis export. */
function analysisBody(kind: AnalysisResult["kind"], cfg: Record<string, unknown>): string[] {
  const lines: string[] = [];
  const metric = typeof cfg.metric === "string" ? cfg.metric : null;
  const dateCol = typeof cfg.dateCol === "string" ? cfg.dateCol : null;
  const dimCol = typeof cfg.dimensionCol === "string" ? cfg.dimensionCol : null;
  const column = typeof cfg.column === "string" ? cfg.column : null;
  switch (kind) {
    case "trend":
    case "kpi": {
      if (!metric) break;
      lines.push(
        `df["${dateCol ?? ""}"] = pd.to_datetime(df["${dateCol ?? metric}"], errors="coerce")`,
        'df = df.dropna(subset=["' + (dateCol ?? metric) + '"])',
        `period = df["${dateCol ?? metric}"].dt.to_period("${cfg.granularity ?? "month"}")`,
        `series = df.groupby(period)["${metric}"].${kind === "kpi" ? "mean" : "sum"}`,
        "print(series)",
      );
      break;
    }
    case "correlation": {
      const cols = Array.isArray(cfg.columns) ? (cfg.columns as string[]) : [];
      if (cols.length === 0) break;
      lines.push(
        `corr = df[${JSON.stringify(cols)}].apply(pd.to_numeric, errors="coerce").corr()`,
        "print(corr.round(4))",
      );
      break;
    }
    case "distribution": {
      if (!column) break;
      lines.push(
        `col = pd.to_numeric(df["${column}"], errors="coerce").dropna()`,
        `print("mean", col.mean(), "std", col.std(), "min", col.min(), "max", col.max())`,
        `print("histogram", np.histogram(col, bins=${Number(cfg.bins) || 10}))`,
      );
      break;
    }
    case "segmentation": {
      const k = Number(cfg.k) || 3;
      if (!dimCol) break;
      lines.push(
        "from sklearn.preprocessing import StandardScaler",
        "from sklearn.cluster import KMeans",
        `features = pd.get_dummies(df[${JSON.stringify([dimCol])}].astype(str))`,
        "X = StandardScaler().fit_transform(features)",
        `model = KMeans(n_clusters=${k}, n_init=10, random_state=42).fit(X)`,
        'df["segment"] = model.labels_',
        'print(df.groupby("segment").size())',
      );
      break;
    }
    default:
      lines.push(
        "# Generic reproducible summary of the dataset this analysis ran on.",
        'print(df.describe(include="all").T)',
      );
  }
  return lines;
}

/** Standalone script for an AnalysisResult (+ the config that produced it). */
export function analysisPythonScript(result: AnalysisResult, cfg: Record<string, unknown>): string {
  const lines = [
    ...header(
      `Reproduce Ledgerly analysis: ${result.title}`,
      `Kind: ${result.kind}. Metric definitions and methodology mirror the engine\nthat produced the in-app result (see methodology below).`,
    ),
    "# ------------------------------------------------------------------",
    "# 1. Load the dataset (adjust the path to your own copy of the file)",
    "# ------------------------------------------------------------------",
    'df = pd.read_csv("dataset.csv")  # ← point at the same file you uploaded',
    "",
    "# Configuration used in-app:",
    `CONFIG = json.loads(r'''${JSON.stringify(cfg)}''')`,
    "",
    ...analysisBody(result.kind, cfg),
    "",
    "# ------------------------------------------------------------------",
    "# 2. Methodology (as computed in-app)",
    "# ------------------------------------------------------------------",
    `METHODOLOGY = ${json(result.methodology)}`,
    `SCOPE = ${json(result.scope)}`,
    "",
  ];
  return lines.join("\n");
}

