/** Standalone OLS reproduction of a what-if projection (same math as the engine). */
export function whatIfPythonScript(result: WhatIfResult, datasetName: string): string {
  // Controls that entered the fit — the script reproduces the same multivariate
  // model the in-app engine used (bivariate when no controls were fitted).
  const controls = result.model.controls ?? [];
  const hasControls = controls.length > 0;
  return [
    ...header(
      `Reproduce Ledgerly what-if: ${result.pctChange > 0 ? "+" : ""}${result.pctChange}% on ${result.driverColumn} → ${result.outcomeColumn}`,
      `Dataset: ${datasetName}. ${hasControls ? "Multiple" : "Ordinary least squares"} regression +\nre-evaluation at the perturbed driver mean${
        hasControls ? " with controls held at their means" : ""
      } (identical math to the in-app engine).`,
    ),
    'df = pd.read_csv("dataset.csv")  # ← point at the same file you uploaded',
    `x = pd.to_numeric(df["${result.driverColumn}"], errors="coerce")`,
    `y = pd.to_numeric(df["${result.outcomeColumn}"], errors="coerce")`,
    ...controls.map((name, i) => `c${i + 1} = pd.to_numeric(df["${name}"], errors="coerce")`),
    "mask = x.notna() & y.notna()" +
      (hasControls ? " & " + controls.map((_, i) => `c${i + 1}.notna()`).join(" & ") : ""),
    "x, y = x[mask], y[mask]",
    ...(hasControls ? controls.map((_, i) => `c${i + 1} = c${i + 1}[mask]`) : []),
    "",
    hasControls
      ? `X = pd.concat([x, ${controls.map((_, i) => `c${i + 1}`).join(", ")}], axis=1)`
      : 'X = x.to_frame("x")',
    "Xc = X - X.mean()",
    "yc = y - y.mean()",
    "beta, *_ = np.linalg.lstsq(Xc.values, yc.values, rcond=None)",
    "intercept = float(y.mean() - np.dot(beta, X.mean().values))",
    "fitted = (Xc.values * beta).sum(axis=1) + y.mean()",
    "r2 = 1 - ((y.values - fitted) ** 2).sum() / ((yc.values) ** 2).sum()",
    "",
    `new_x = x.mean() * (1 + ${result.pctChange} / 100)`,
    // Controls held at their means ⇒ their centered terms vanish, so the
    // projection is intercept + slope·new_x — exactly like the in-app engine.
    "after = intercept + float(beta[0]) * new_x",
    "before = y.mean()",
    "",
    'print(f"slope={float(beta[0]):.6f} intercept={intercept:.6f} r2={r2:.4f}")',
    'print(f"before={before:.6f} after={after:.6f} delta={after - before:.6f}")',
    "",
    `# In-app result (fallback=${result.fallback}): before=${result.beforeValue} after=${result.afterValue} delta=${result.delta}`,
    `# Model: ${json(result.model)}`,
    "",
  ].join("\n");
}

