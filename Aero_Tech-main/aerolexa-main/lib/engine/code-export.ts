/**
 * Phase 1.5 — "Export runnable code": generate a standalone Python script
 * that reproduces a computed result outside Ledgerly, using the real
 * pandas/scipy/sklearn calls that correspond to the engine's math.
 *
 * Pure string generation — unit-tested; the acceptance test executes the
 * regression script in a real Python interpreter and compares numbers.
 */

import type { AnalysisResult, ModelCard, WhatIfResult } from "@/lib/types";

export interface HypothesisExportInput {
  kind: "t-test" | "chi-square" | "anova";
  groups?: number[][];
  table?: number[][];
}

/** Compact single-line JSON — safe to embed inside Python source files. */
function json(obj: unknown): string {
  return JSON.stringify(obj);
}

function header(title: string, sub: string): string[] {
  return [
    '"""',
    `${title}`,
    "",
    sub,
    "",
    "Generated by Ledgerly (Phase 1.5 export). Requires: pandas, scipy, scikit-learn.",
    '"""',
    "",
    "import json",
    "import numpy as np",
    "import pandas as pd",
    "",
  ];
}

