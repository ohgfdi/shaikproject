/**
 * Copilot integration (WS4.4).
 *
 * Unified interface for AI-assisted authoring in notebooks and dashboards.
 * Handles: code generation, chart recommendation, insight explanation,
 * formula suggestion, and context-aware chat.
 */

import type { ChartKind, ColumnDef, ChartSpec, DashboardWidget, NotebookCell } from "@/lib/types";

import {
  recommendChartsWithLLM,
  buildChartSpec,
  type ChartRecommendation,
  type RecommendationRequest,
} from "./chart-recommend";
import { getLLMClient } from "./client";
import { generateCode, type NLToCodeRequest, type NLToCodeResult } from "./nl-to-code";

export type CopilotContextType = "notebook" | "dashboard" | "report" | "analysis";

export interface CopilotRequest {
  /** User's natural language query */
  query: string;
  /** Context type */
  contextType: CopilotContextType;
  /** Dataset schema for grounding */
  columns: ColumnDef[];
  /** Dataset name */
  datasetName: string;
  /** Current notebook/dashboard state */
  state?: {
    /** Notebook cells (for notebook context) */
    cells?: NotebookCell[];
    /** Dashboard widgets (for dashboard context) */
    widgets?: DashboardWidget[];
    /** Current cell/widget being edited */
    activeId?: string;
    /** Recent chat history */
    history?: Array<{ role: "user" | "assistant"; content: string }>;
  };
}

export interface CopilotResponse {
  /** Type of response */
  type: "code" | "chart" | "explanation" | "formula" | "chat";
  /** Generated content */
  content: string;
  /** Structured data for UI rendering */
  data?: {
    /** Code generation result */
    code?: NLToCodeResult;
    /** Chart recommendation */
    chart?: { recommendations: ChartRecommendation[]; specs: Array<Pick<ChartRecommendation, "type" | "mapping">> };
    /** Formula/DAX suggestion */
    formula?: { dax: string; explanation: string };
    /** Insight explanation */
    insight?: { title: string; description: string; evidence: string };
  };
  /** Confidence score (0-1) */
  confidence: number;
  /** Suggested follow-up questions */
  followUp?: string[];
  /** Whether this was generated by LLM or deterministic fallback */
  source: "llm" | "deterministic";
}

/** System prompt for copilot chat */
const COPILOT_SYSTEM = `You are Ledgerly Copilot, an expert data analyst assistant embedded in a notebook/dashboard environment.
You help users explore data, write code, create visualizations, and understand their data.

Guidelines:
- Be concise but thorough
- Always reference actual column names from the schema
- When suggesting code, provide complete, runnable snippets
- When explaining insights, cite specific numbers from the data
- If unsure, ask clarifying questions
- Never hallucinate column names or data values`;

/** Classify user intent from query */
function classifyIntent(query: string): "code" | "chart" | "explanation" | "formula" | "chat" {
  const q = query.toLowerCase();
  if (
    q.includes("chart") ||
    q.includes("plot") ||
    q.includes("visualiz") ||
    q.includes("graph") ||
    q.includes("show") ||
    q.includes("display")
  ) {
    return "chart";
  }
  if (q.includes("dax") || q.includes("measure") || q.includes("calculat") || q.includes("formula")) {
    return "formula";
  }
  if (
    q.includes("code") ||
    q.includes("sql") ||
    q.includes("python") ||
    q.includes("pandas") ||
    q.includes("script") ||
    q.includes("query")
  ) {
    return "code";
  }
  if (
    q.includes("why") ||
    q.includes("explain") ||
    q.includes("what does") ||
    q.includes("how") ||
    q.includes("insight") ||
    q.includes("meaning")
  ) {
    return "explanation";
  }
  return "chat";
}

/** Build context summary for LLM */
function buildContextSummary(req: CopilotRequest): string {
  const parts: string[] = [];
  parts.push(`Dataset: "${req.datasetName}"`);
  parts.push(`Columns: ${req.columns.map((c) => `${c.name} (${c.type})`).join(", ")}`);

  // Bound to a local so the narrowing below survives into the callbacks —
  // narrowing a property of a parameter is reset inside closures.
  const state = req.state;

  if (state?.cells?.length) {
    parts.push(`Notebook has ${state.cells.length} cells`);
    if (state.activeId) {
      const active = state.cells.find((c) => c.id === state.activeId);
      if (active) parts.push(`Active cell (${active.kind}): ${active.content?.slice(0, 200)}`);
    }
  }

  if (state?.widgets?.length) {
    parts.push(`Dashboard has ${state.widgets.length} widgets`);
    if (state.activeId) {
      const active = state.widgets.find((w) => w.id === state.activeId);
      if (active) parts.push(`Active widget (${active.type}): ${active.title}`);
    }
  }

  if (state?.history?.length) {
    parts.push(
      `Recent conversation: ${state.history
        .slice(-3)
        .map((h) => `${h.role}: ${h.content.slice(0, 100)}`)
        .join("; ")}`,
    );
  }

  return parts.join("\n");
}

/** Main copilot handler */
export async function handleCopilotRequest(req: CopilotRequest): Promise<CopilotResponse> {
  const intent = classifyIntent(req.query);
  const contextSummary = buildContextSummary(req);

  // 1. Chart requests
  if (intent === "chart") {
    const recReq: RecommendationRequest = {
      columns: req.columns,
      intent: "comparison", // default
      max: 5,
    };
    const recommendations = await recommendChartsWithLLM(recReq);
    return {
      type: "chart",
      content: `Here are ${recommendations.length} recommended visualizations for your data:`,
      data: {
        chart: {
          recommendations,
          specs: recommendations.map((r) => ({ type: r.type, mapping: r.mapping })),
        },
      },
      confidence: Math.max(...recommendations.map((r) => r.confidence)),
      source: "llm",
      followUp: ["Can you customize the colors?", "Add a filter to this chart", "Create a dashboard with these charts"],
    };
  }

  // 2. Code generation
  if (intent === "code") {
    // Determine target from query
    let target: "dsl" | "sql" | "dax" | "python" | "pandas" = "dsl";
    if (req.query.toLowerCase().includes("sql")) target = "sql";
    else if (req.query.toLowerCase().includes("dax")) target = "dax";
    else if (req.query.toLowerCase().includes("python") || req.query.toLowerCase().includes("pandas"))
      target = "pandas";

    const nlReq: NLToCodeRequest = {
      request: req.query,
      columns: req.columns,
      datasetName: req.datasetName,
      target,
      context: req.state?.cells?.map((c) => `${c.kind}: ${c.content}`).join("\n"),
    };

    const result = await generateCode(nlReq);

    return {
      type: "code",
      content: result.code ? `Here's the ${target.toUpperCase()} code:` : "I couldn't generate code for that request.",
      data: { code: result },
      confidence: result.success ? 0.9 : 0.3,
      source: result.success ? "llm" : "deterministic",
      followUp: result.success
        ? ["Run this code", "Explain what it does", "Modify the output format"]
        : ["Try rephrasing your request", "Use the deterministic DSL instead"],
    };
  }

  // 3. Formula/DAX
  if (intent === "formula") {
    const client = getLLMClient();
    const prompt = `${COPILOT_SYSTEM}\n\n${contextSummary}\n\nUser wants a DAX formula: ${req.query}\n\nGenerate a complete DAX measure expression. Use only columns from the schema.`;

    try {
      const dax = await client.completeText(prompt, { system: COPILOT_SYSTEM, temperature: 0.1, maxTokens: 500 });
      return {
        type: "formula",
        content: `Here's a DAX formula for your request:`,
        data: { formula: { dax, explanation: "Generated DAX measure" } },
        confidence: 0.85,
        source: "llm",
        followUp: ["Add a filter to this measure", "Create a calculated column instead", "Explain the filter context"],
      };
    } catch {
      return {
        type: "formula",
        content: "I couldn't generate a DAX formula. Try being more specific about the calculation you need.",
        confidence: 0.2,
        source: "deterministic",
      };
    }
  }

  // 4. Explanation / Insight
  if (intent === "explanation") {
    const client = getLLMClient();
    const prompt = `${COPILOT_SYSTEM}\n\n${contextSummary}\n\nUser asks: "${req.query}"\n\nProvide a clear, data-driven explanation. Reference specific columns and potential patterns.`;

    try {
      const explanation = await client.completeText(prompt, {
        system: COPILOT_SYSTEM,
        temperature: 0.2,
        maxTokens: 800,
      });
      return {
        type: "explanation",
        content: explanation,
        data: { insight: { title: "Explanation", description: explanation, evidence: "Based on dataset schema" } },
        confidence: 0.8,
        source: "llm",
        followUp: ["Show me the data behind this", "Create a visualization for this", "What if we filter by X?"],
      };
    } catch {
      return {
        type: "explanation",
        content: "I couldn't generate an explanation. Try asking about a specific column or pattern.",
        confidence: 0.2,
        source: "deterministic",
      };
    }
  }

  // 5. General chat
  const client = getLLMClient();
  const messages = [
    { role: "system" as const, content: COPILOT_SYSTEM },
    { role: "user" as const, content: `${contextSummary}\n\nUser: ${req.query}` },
  ];

  try {
    const response = await client.complete({ messages, temperature: 0.3, maxTokens: 800 });
    const content = response.choices[0]?.message?.content ?? "I'm not sure how to help with that.";
    return {
      type: "chat",
      content,
      confidence: 0.7,
      source: "llm",
      followUp: [
        "Can you show me an example?",
        "What other analyses can I do?",
        "How do I create a dashboard from this?",
      ],
    };
  } catch {
    return {
      type: "chat",
      content:
        "I'm having trouble connecting to the AI service. You can still use the deterministic features like /llm DSL commands.",
      confidence: 0.3,
      source: "deterministic",
    };
  }
}

/** Notebook-specific: generate cell from request */
export async function copilotNotebookCell(req: CopilotRequest): Promise<{ kind: string; content: string } | null> {
  const result = await generateCode({
    request: req.query,
    columns: req.columns,
    datasetName: req.datasetName,
    target: "dsl",
    context: req.state?.cells?.map((c) => `${c.kind}: ${c.content}`).join("\n"),
  });

  if (result.success && result.code) {
    return { kind: "code", content: result.code };
  }
  return null;
}

/** Dashboard-specific: suggest widget from request */
export async function copilotDashboardWidget(req: CopilotRequest): Promise<{
  type: ChartKind;
  spec: ChartSpec;
  title: string;
} | null> {
  const recReq: RecommendationRequest = {
    columns: req.columns,
    intent: "comparison",
    max: 1,
  };
  const recommendations = await recommendChartsWithLLM(recReq);
  const rec = recommendations[0];
  if (!rec) return null;

  // A "table" recommendation has no ChartSpec; let the caller fall back.
  const spec = buildChartSpec(rec, req.columns);
  if (!spec) return null;

  return {
    type: spec.kind,
    spec,
    title: rec.reason,
  };
}

