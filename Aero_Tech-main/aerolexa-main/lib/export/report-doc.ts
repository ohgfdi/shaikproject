import { esc, exportShell, sectionHtml } from "@/lib/export/html";
import type { ReportSection, ReportSectionSource } from "@/lib/types";

/**
 * Shared professional report document renderer.
 *
 * Used by BOTH the manual export route (/export/reports/[id]) and the
 * scheduled-report runner, so a stakeholder receives exactly the same
 * document regardless of how it was produced.
 *
 * Professional structure: cover header → provenance/metadata table →
 * table of contents → body sections (each carrying its own source tag) →
 * "Sources & verification" block → footer with scope disclosure.
 * Everything here renders what is in the report; nothing is invented.
 */
export interface ReportDocMeta {
  title: string;
  projectName: string | null;
  authorName: string;
  version: number;
  generatedAt: Date;
  datasetName?: string | null;
  datasetRowCount?: number | null;
  datasetColumnCount?: number | null;
  /** Where the document was produced by: manual export vs scheduled run. */
  productionNote: string;
}

function metadataTable(meta: ReportDocMeta): string {
  const rows: [string, string][] = [
    ["Prepared by", meta.authorName],
    ["Project", meta.projectName ?? "—"],
    ["Version", `v${meta.version}`],
    ["Generated", meta.generatedAt.toLocaleString("en-US", { dateStyle: "long", timeStyle: "short" })],
    ["Source dataset", meta.datasetName ?? "—"],
  ];
  if (meta.datasetRowCount !== null && meta.datasetRowCount !== undefined) {
    rows.push(["Rows analysed", meta.datasetRowCount.toLocaleString()]);
  }
  if (meta.datasetColumnCount !== null && meta.datasetColumnCount !== undefined) {
    rows.push(["Columns", String(meta.datasetColumnCount)]);
  }
  rows.push(["Produced", meta.productionNote]);
  return `<table class="meta-table">${rows
    .map(([k, v]) => `<tr><th scope="row">${esc(k)}</th><td>${esc(v)}</td></tr>`)
    .join("")}</table>`;
}

function tableOfContents(sections: ReportSection[]): string {
  if (sections.length < 2) return "";
  const items = sections
    .map((s, i) => `<li><a href="#sec-${i}"><span class="toc-num">${i + 1}</span>${esc(s.heading)}</a></li>`)
    .join("");
  return `<nav class="toc" aria-label="Table of contents"><h2>Contents</h2><ol>${items}</ol></nav>`;
}

const SOURCE_LABELS: Record<ReportSectionSource["kind"], string> = {
  dataset: "Dataset",
  profile: "Dataset profile",
  analysis: "Analysis",
  insight: "Insight",
  manual: "Editorial",
  awaiting: "Awaiting evidence",
};

/** Unique, non-editorial sources actually used by the body of the report. */
function collectSources(sections: ReportSection[]): { label: string; kind: ReportSectionSource["kind"] }[] {
  const out: { label: string; kind: ReportSectionSource["kind"] }[] = [];
  const seen = new Set<string>();
  for (const s of sections) {
    const src = s.source;
    if (!src || src.kind === "awaiting" || src.kind === "manual") continue;
    const key = `${src.kind}:${src.label ?? src.id ?? s.heading}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ label: src.label ?? s.heading, kind: src.kind });
  }
  return out;
}

/** The honesty block: which artifacts each figure traces back to. */
function sourcesPanel(sections: ReportSection[]): string {
  const sources = collectSources(sections);
  const awaitingCount = sections.filter((s) => s.source?.kind === "awaiting").length;
  const rows = sources.map(
    (s) =>
      `<li><span class="src-kind">${SOURCE_LABELS[s.kind] ?? s.kind}</span><span class="src-label">${esc(s.label)}</span></li>`,
  );
  return `<section class="sources-block">
  <h2>Sources &amp; verification</h2>
  <p class="sources-lead">Every figure in this document is computed from the artifacts listed below. Ledgerly does not project, extrapolate or invent numbers — each one traces to a stored dataset, analysis or insight.</p>
  ${
    rows.length
      ? `<ul class="sources-list">${rows.join("")}</ul>`
      : `<p class="sources-empty">No data-backed sources yet — open the workspace and connect a dataset of interest.</p>`
  }
  ${
    awaitingCount > 0
      ? `<p class="sources-note">${awaitingCount} section${awaitingCount > 1 ? "s" : ""} ${awaitingCount > 1 ? "are" : "is"} awaiting evidence and will state that explicitly rather than guess.</p>`
      : ""
  }
</section>`;
}

function footer(meta: ReportDocMeta): string {
  const scope = meta.datasetName
    ? `Scope: “${esc(meta.datasetName)}”. Verify against operational data before acting.`
    : "Open the workspace for the underlying calculations.";
  return `<footer class="footer">
  <span>Generated by Ledgerly — every figure computed from the source artifacts with deterministic, traceable logic.</span>
  <span>${scope}</span>
</footer>`;
}

export function renderReportDocument(sections: ReportSection[], meta: ReportDocMeta): string {
  const dated = meta.generatedAt.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const body = `
    <div class="no-print" style="display:flex;justify-content:flex-end;gap:8px;margin-bottom:12px">
      <button onclick="window.print()" style="font:inherit;font-size:13px;padding:6px 14px;border-radius:6px;border:1px solid #5AA8AA;background:#5AA8AA;color:#fff;cursor:pointer">Print / Save as PDF</button>
    </div>
    <header class="doc-header">
      <p class="doc-kicker">Executive report · ${esc(meta.projectName ?? "Ledgerly")}</p>
      <h1>${esc(meta.title)}</h1>
      <p class="doc-sub">v${meta.version} · ${dated} · Prepared by ${esc(meta.authorName)}</p>
    </header>
    ${metadataTable(meta)}
    ${tableOfContents(sections)}
    <div class="doc-body">
    ${sections
      .map(
        (s, i) =>
          `<section id="sec-${i}" class="doc-section"><span class="sec-number">${i + 1}</span>${sectionHtml(s)}</section>`,
      )
      .join("")}
    </div>
    ${sourcesPanel(sections)}
    ${footer(meta)}`;

  return exportShell({ title: `${meta.title} — report`, body });
}
