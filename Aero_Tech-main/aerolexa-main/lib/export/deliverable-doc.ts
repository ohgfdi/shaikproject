import { esc, exportShell, htmlForText } from "@/lib/export/html";
import type { DeliverablePreview, DeliverablePreviewSection } from "@/lib/server/deliverables";

export interface DeliverableDocMeta {
  firmName: string;
  signatoryName: string | null;
  signatoryDesignation: string | null;
  issuedFor: string | null;
  generatedAt: Date;
}

const SOURCE_LABELS: Record<string, string> = {
  WORKING_PAPER: "Working paper",
  ANALYSIS: "Analysis",
  DATASET: "Dataset",
  COMPUTED: "Computed",
  MANUAL: "Manual",
};

function provenanceBadge(section: DeliverablePreviewSection): string {
  const kind = section.source ?? "MANUAL";
  const label = SOURCE_LABELS[kind] ?? kind;
  const awaiting = kind === "MANUAL" && section.body.trim().length === 0;
  const color = awaiting ? "#B45309" : "#5AA8AA";
  const bg = awaiting ? "#FEF3C7" : "#ECF8F8";
  const dot = awaiting ? "⏳" : "●";
  const ref = section.sourceRef ?? "";
  return `<p class="section-source" style="display:inline-block;margin:2px 0 0;padding:2px 10px;border-radius:999px;font-size:11px;color:${color};background:${bg}">${dot} ${esc(label)}${ref ? ` — ${esc(ref)}` : ""}</p>`;
}

function sectionHtml(section: DeliverablePreviewSection, index: number): string {
  const body =
    section.body.trim().length > 0
      ? htmlForText(section.body)
      : `<p style="color:#9CA3AF;font-style:italic">Awaiting content for this part.</p>`;
  return `<section id="part-${index}" class="doc-section">
    <span class="sec-number">${index + 1}</span>
    <h2 style="font-size:18px;margin:1.4em 0 0.5em;color:#111827">${esc(section.heading)}</h2>
    ${provenanceBadge(section)}
    ${body}
    ${section.redacted ? `<p style="font-size:11px;color:#6B7280;margin-top:6px">Some identifiers were redacted for the client-facing copy.</p>` : ""}
  </section>`;
}

function tracePanel(preview: DeliverablePreview): string {
  const t = preview.trace;
  const rows: [string, string][] = [
    ["Total parts", String(t.totalParts)],
    ["Traced to evidence", String(t.tracedParts)],
    ["Manual/computed text", String(t.manualParts)],
    ["Complete (every part traced)", t.complete ? "Yes" : "No"],
  ];
  return `<section class="sources-block">
    <h2>Traceability (working-paper to report)</h2>
    <p class="sources-lead">This deliverable preserves a trace from each numbered part back to its underlying evidence. When a part remains untraced, the document states it explicitly rather than inventing numbers.</p>
    <table style="width:100%;border-collapse:collapse;font-size:12.5px;margin-bottom:10px">
      ${rows.map(([k, v]) => `<tr><th style="text-align:left;padding:4px 6px;color:#6B7280">${esc(k)}</th><td style="padding:4px 6px">${esc(v)}</td></tr>`).join("")}
    </table>
    ${
      t.workingPaperRefs.length
        ? `<p style="margin:0;font-size:12px;color:#374151"><strong>Working paper refs:</strong> ${t.workingPaperRefs.map((r) => esc(r)).join(", ")}</p>`
        : ""
    }
  </section>`;
}

export function renderDeliverableDocument(preview: DeliverablePreview, meta: DeliverableDocMeta): string {
  const v = preview.version;
  const content = v.content;
  const dated = meta.generatedAt.toLocaleDateString("en-IN", { year: "numeric", month: "long", day: "numeric" });
  const body = `
    <div class="no-print" style="display:flex;justify-content:flex-end;gap:8px;margin-bottom:12px">
      <button onclick="window.print()" style="font:inherit;font-size:13px;padding:6px 14px;border-radius:6px;border:1px solid #5AA8AA;background:#5AA8AA;color:#fff;cursor:pointer">Print / Save as PDF</button>
    </div>
    <header class="doc-header">
      <p class="doc-kicker">${esc(content?.notation ?? v.formatLabel)}</p>
      <h1>${esc(preview.title)}</h1>
      <p class="doc-sub">Revision ${v.revision} · ${v.variant} · ${dated}</p>
    </header>
    <table class="meta-table">
      <tr><th scope="row">Prepared for</th><td>${esc(meta.issuedFor ?? "Client")}</td></tr>
      <tr><th scope="row">Firm</th><td>${esc(meta.firmName)}</td></tr>
      <tr><th scope="row">Signatory</th><td>${meta.signatoryName ? esc(meta.signatoryName) : "—"}${meta.signatoryDesignation ? ` — ${esc(meta.signatoryDesignation)}` : ""}</td></tr>
      <tr><th scope="row">Effective date</th><td>${esc(content?.dateLabel ?? dated)}</td></tr>
      <tr><th scope="row">Status at issue</th><td>${esc(v.status)}</td></tr>
    </table>
    ${preview.sections.map((s, i) => sectionHtml(s, i)).join("")}
    ${tracePanel(preview)}
    <footer class="footer">
      <span>Generated by Ledgerly — this deliverable is traceable to its underlying working papers and stored artifacts.</span>
      <span>Variant: ${esc(v.variant)} · Revision ${v.revision}</span>
    </footer>`;
  return exportShell({ title: preview.title, body });
}
