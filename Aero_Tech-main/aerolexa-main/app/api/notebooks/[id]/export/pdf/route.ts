import { NextResponse } from "next/server";

import { ApiError, requireAuth } from "@/lib/auth/guard";
import { prisma } from "@/lib/db";
import { exportShell, esc } from "@/lib/export/html";
import { renderNotebookToPdf } from "@/lib/export/pdf";
import { parseJsonArray } from "@/lib/json";
import { logActivity } from "@/lib/server/activity";
import { toErrorResponse } from "@/lib/server/api";
import { requireRowRole } from "@/lib/server/members";
import { requireModule } from "@/lib/server/modules";
import type { NotebookCell, NotebookCellOutput } from "@/lib/types";

export const dynamic = "force-dynamic";

/** GET /api/notebooks/:id/export/pdf — download the notebook as PDF. */
export async function GET(_request: Request, props: { params: Promise<{ id: string }> }) {
  const params = await props.params;
  try {
    requireModule("NOTEBOOK_ENABLED");
    const ctx = await requireAuth();
    const notebook = await prisma.notebook.findUnique({
      where: { id: params.id },
      include: { dataset: { select: { name: true } } },
    });
    if (!notebook) throw new ApiError(404, "NOT_FOUND", "Notebook not found.");
    await requireRowRole(ctx, notebook, "VIEWER");

    const cells = parseJsonArray<NotebookCell>(notebook.cells, []);

    // Build HTML representation of the notebook
    const html = buildNotebookHtml(notebook.title, notebook.dataset?.name ?? null, cells);

    const pdfBuffer = await renderNotebookToPdf(html, `notebook-${notebook.id.slice(0, 8)}`);

    await logActivity(
      ctx,
      "NOTEBOOK_EXPORTED",
      `Notebook "${notebook.title}" exported as PDF (${cells.length} cells)`,
      notebook.projectId,
      { notebookId: notebook.id, format: "pdf" },
    );

    return new NextResponse(new Uint8Array(pdfBuffer), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="notebook-${notebook.id.slice(0, 8)}.pdf"`,
        "Content-Length": pdfBuffer.length.toString(),
      },
    });
  } catch (err) {
    return toErrorResponse(err);
  }
}

function buildNotebookHtml(title: string, datasetName: string | null, cells: NotebookCell[]): string {
  const cover = `
    <div class="cover">
      <h1>${esc(title)}</h1>
      <p>${datasetName ? `Dataset: ${esc(datasetName)}` : "No dataset attached"}</p>
      <p style="font-size:12px;color:#5AA8AA">Generated by Ledgerly — notebook export</p>
    </div>
  `;

  const body = cells
    .map((cell, i) => {
      let content = "";
      if (cell.kind === "markdown") {
        content = `<p class="whitespace-pre-wrap bg-background px-3 py-2 text-sm leading-relaxed text-foreground">${esc(cell.content)}</p>`;
      } else if (cell.kind === "code") {
        content = `<pre class="thin-scroll overflow-x-auto bg-background px-3 py-2.5 font-mono text-[13px] whitespace-pre-wrap text-foreground">${esc(cell.content)}</pre>`;
      } else if (cell.kind === "widget" && cell.widget) {
        content = `
        <div class="flex flex-wrap items-center gap-3 bg-background px-3 py-3">
          <label className="text-sm font-medium text-foreground">${esc(cell.widget.label ?? cell.widget.variable)}</label>
          <span className="text-caption text-muted">binds {{${esc(cell.widget.variable)}}}</span>
        </div>
      `;
      } else {
        content = `<pre class="thin-scroll overflow-x-auto bg-background px-3 py-2.5 font-mono text-[13px] whitespace-pre-wrap text-foreground">${esc(cell.content)}</pre>`;
      }

      // Add output if present
      let outputHtml = "";
      if (cell.output) {
        outputHtml = outputToHtml(cell.output);
      }

      return `
      <li class="card overflow-hidden page-break">
        <div class="border-b border-line bg-surface px-3 py-1.5">
          <span class="text-caption font-medium text-foreground">${esc(cell.kind)}</span>
          <span className="ml-2 text-caption text-muted">Cell ${i + 1}</span>
        </div>
        ${content}
        ${outputHtml}
      </li>
    `;
    })
    .join("");

  const notes = `
    <footer class="footer">
      <span>Generated by Ledgerly — every output computed from the source data with deterministic, traceable logic.</span>
    </footer>
  `;

  return exportShell({
    title: `${title} — notebook`,
    body: `<ol class="flex flex-col gap-3">${cover}${body}</ol>${notes}`,
  });
}

function outputToHtml(output: NotebookCellOutput): string {
  if (output.type === "error") {
    return `<div role="alert" class="border-t border-danger/30 bg-danger/5 px-3 py-2.5 font-mono text-[13px] text-danger">${esc(output.message)}</div>`;
  }
  if (output.type === "note") {
    return `<div class="border-t border-info/30 bg-info/5 px-3 py-2.5 text-sm"><p class="font-medium text-foreground">${esc(output.title)}</p><p class="mt-1 text-muted">${esc(output.detail)}</p></div>`;
  }
  if (output.type === "text") {
    return `<pre class="thin-scroll border-t border-line bg-background px-3 py-2.5 font-mono text-[13px] whitespace-pre-wrap text-foreground">${esc(output.text)}</pre>`;
  }
  if (output.type === "chart") {
    return `<div class="border-t border-line px-3 py-3"><p class="mb-1 text-sm font-medium text-foreground">${esc(output.chart.title)}</p></div>`;
  }
  if (output.type === "table") {
    return `<div class="border-t border-line px-3 py-3">${tableHtml(output.title, output.columns, output.rows)}</div>`;
  }
  if (output.type === "stats") {
    return `<div class="border-t border-line px-3 py-3"><p class="mb-2 text-caption font-medium text-foreground">${esc(output.title)}</p>${statsHtml(output.stats)}</div>`;
  }
  if (output.type === "sql-result") {
    return `<div class="border-t border-line px-3 py-3"><p class="mb-1 text-sm font-medium text-foreground">${esc(output.title)}</p><p class="mb-2 text-caption text-muted">${esc(output.note)}</p></div>`;
  }
  if (output.type === "image") {
    return `<div class="border-t border-line px-3 py-3"><img src="data:${output.image.mimeType};base64,${output.image.data}" alt="Python chart output" className="h-auto max-w-full" /></div>`;
  }
  if (output.type === "pivot-result") {
    return `<div class="border-t border-line px-3 py-3"><p class="mb-1 text-sm font-medium text-foreground">${esc(output.title)}</p><p class="text-caption text-muted">${output.rowHeaders.length} rows × ${output.columnHeaders.length} columns</p></div>`;
  }
  if (output.type === "map-result") {
    return `<div class="border-t border-line px-3 py-3"><p class="mb-1 text-sm font-medium text-foreground">${esc(output.title)}</p><p class="text-caption text-muted">${output.points.length} points</p></div>`;
  }
  return `<div class="border-t border-line px-3 py-2.5 text-sm text-muted">Output rendered (${output.type})</div>`;
}

function tableHtml(
  title: string,
  columns: { key: string; label: string; format?: "number" | "pct" | "date" | "text" }[],
  rows: (string | number | null)[][],
): string {
  return `
    <table style="border-collapse:collapse;width:100%;font-size:12px;margin:0.5em 0 1.2em">
      <caption style="font-weight:600;margin-bottom:4px">${esc(title)}</caption>
      <thead><tr>${columns.map((c) => `<th style="text-align:left;padding:6px 8px;border-bottom:1px solid #E5E7EB">${esc(c.label)}</th>`).join("")}</tr></thead>
      <tbody>${rows
        .slice(0, 50)
        .map(
          (r) =>
            `<tr>${columns.map((c, i) => `<td style="padding:5px 8px;border-bottom:1px solid #F3F4F6;color:#374151">${r[i] === null || r[i] === undefined ? "—" : esc(String(r[i]))}</td>`).join("")}</tr>`,
        )
        .join("")}</tbody>
    </table>`;
}

function statsHtml(stats: { label: string; value: string; hint?: string }[]): string {
  return `<dl class="grid grid-cols-2 gap-x-4 gap-y-1.5 sm:grid-cols-3">${stats.map((s) => `<div key=${s.label} class="text-sm"><dt class="text-caption text-muted">${esc(s.label)}</dt><dd class="tabular-nums font-medium text-foreground" title=${esc(s.hint ?? "")}>${esc(s.value)}</dd></div>`).join("")}</dl>`;
}
