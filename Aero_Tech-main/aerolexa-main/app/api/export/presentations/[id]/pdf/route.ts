// TENANCY_GLOBAL_MARKER: tenancy-audit: global-operator - presentation PDF export is a deployment-wide aggregate operation
import { NextResponse } from "next/server";

import { requireAuth } from "@/lib/auth/guard";
import { prisma } from "@/lib/db";
import { exportShell, slideHtml, esc } from "@/lib/export/html";
import { renderPresentationToPdf } from "@/lib/export/pdf";
import { presentationSlides } from "@/lib/serialize";
import { logActivity } from "@/lib/server/activity";

export const dynamic = "force-dynamic";

export async function GET(_request: Request, props: { params: Promise<{ id: string }> }) {
  const params = await props.params;
  try {
    const ctx = await requireAuth();
    const presentation = await prisma.presentation.findUnique({
      where: { id: params.id },
      include: { createdBy: { select: { name: true } }, project: { select: { name: true } } },
    });
    if (!presentation || presentation.workspaceId !== ctx.workspace.id) {
      return NextResponse.json(
        { ok: false, error: { code: "NOT_FOUND", message: "Presentation not found." } },
        { status: 404 },
      );
    }

    const slides = presentationSlides(presentation);
    const cover = `<div class="cover"><h1>${esc(presentation.title)}</h1><p>${esc(presentation.project?.name ?? "")} · ${esc(presentation.createdBy.name)} · ${new Date().toLocaleDateString()}</p><p style="font-size:12px;color:#5AA8AA">Generated by Ledgerly — prototype deck</p></div>`;
    const body =
      cover +
      slides
        .map((s, i) => {
          const notes = s.notes
            ? `<p style="font-size:10px;color:#9CA3AF;font-style:italic;margin:8px 0 0">Speaker notes: ${esc(s.notes)}</p>`
            : "";
          return `<div class="${i === 0 ? "" : "page-break"}">${slideHtml(s)}${notes}</div>`;
        })
        .join("");

    const html = exportShell({ title: `${presentation.title} — deck`, body });
    const pdfBuffer = await renderPresentationToPdf(html, `deck-${presentation.id.slice(0, 8)}`);

    await logActivity(
      ctx,
      "PRESENTATION_EXPORTED",
      `Presentation "${presentation.title}" exported as PDF`,
      presentation.projectId,
      { presentationId: presentation.id, format: "pdf" },
    );

    return new NextResponse(new Uint8Array(pdfBuffer), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="deck-${presentation.id.slice(0, 8)}.pdf"`,
        "Content-Length": pdfBuffer.length.toString(),
      },
    });
  } catch (err) {
    console.error("PDF export failed:", err);
    return NextResponse.json(
      { ok: false, error: { code: "PDF_EXPORT_FAILED", message: "Failed to generate PDF." } },
      { status: 500 },
    );
  }
}
