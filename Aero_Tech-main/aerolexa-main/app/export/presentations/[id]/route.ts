import { NextResponse } from "next/server";

import { requireAuth } from "@/lib/auth/guard";
import { prisma } from "@/lib/db";
import { exportShell, slideHtml, esc } from "@/lib/export/html";
import { presentationSlides } from "@/lib/serialize";
import { logActivity } from "@/lib/server/activity";

export const dynamic = "force-dynamic";

export async function GET(_request: Request, props: { params: Promise<{ id: string }> }) {
  const params = await props.params;
  const ctx = await requireAuth();
  const presentation = await prisma.presentation.findUnique({
    where: { id: params.id },
    include: { createdBy: { select: { name: true } }, project: { select: { name: true } } },
  });
  if (!presentation || presentation.workspaceId !== ctx.workspace.id) {
    return NextResponse.json(
      { ok: false, error: { code: "NOT_FOUND", message: "Presentation not found." } },
      { status: 404 },
    );
  }

  const slides = presentationSlides(presentation);
  const cover = `<div class="cover"><h1>${esc(presentation.title)}</h1><p>${esc(presentation.project?.name ?? "")} · ${esc(presentation.createdBy.name)} · ${new Date().toLocaleDateString()}</p><p style="font-size:12px;color:#5AA8AA">Generated by Ledgerly — prototype deck (print or “Save as PDF”)</p></div>`;
  const body =
    cover +
    slides
      .map((s, i) => {
        const notes = s.notes
          ? `<p style="font-size:10px;color:#9CA3AF;font-style:italic;margin:8px 0 0">Speaker notes: ${esc(s.notes)}</p>`
          : "";
        return `<div class="${i === 0 ? "" : "page-break"}">${slideHtml(s)}${notes}</div>`;
      })
      .join("");

  await logActivity(
    ctx,
    "PRESENTATION_EXPORTED",
    `Presentation “${presentation.title}” exported`,
    presentation.projectId,
    { presentationId: presentation.id },
  );

  return new NextResponse(exportShell({ title: `${presentation.title} — deck`, body }), {
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Content-Disposition": `inline; filename="deck-${presentation.id.slice(0, 8)}.html"`,
    },
  });
}
